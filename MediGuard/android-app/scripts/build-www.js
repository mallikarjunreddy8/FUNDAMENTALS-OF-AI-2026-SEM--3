// Builds android-app/www from ../web for the Android app:
//  - the same phone app (web/), with the OCR engine and English data stored locally (works offline)
//  - app-config.js: version number + GitHub repo for the update check
//  - update.js: shows "Update available" when GitHub has a newer release
// Usage: APP_VERSION=1.0.7 node scripts/build-www.js
const fs = require("fs");
const path = require("path");

const ROOT = path.resolve(__dirname, "..");
const WEB = path.resolve(ROOT, "../web");
const WWW = path.join(ROOT, "www");
const NM = path.join(ROOT, "node_modules");
const version = process.env.APP_VERSION || "1.0.0";
const repo = process.env.APP_REPO || "mallikarjunreddy8/FUNDAMENTALS-OF-AI-2026-SEM--3";

fs.rmSync(WWW, { recursive: true, force: true });
fs.cpSync(WEB, WWW, { recursive: true, filter: (src) => !/[\\/]test([\\/]|$)/.test(src) });

// OCR engine + English language data, served from inside the app
fs.mkdirSync(path.join(WWW, "lib/core"), { recursive: true });
fs.mkdirSync(path.join(WWW, "lib/lang"), { recursive: true });
for (const f of ["tesseract-core-lstm.wasm.js", "tesseract-core-simd-lstm.wasm.js",
                 "tesseract-core.wasm.js", "tesseract-core-simd.wasm.js"]) {   // the last two include orientation detection
  fs.copyFileSync(path.join(NM, "tesseract.js-core", f), path.join(WWW, "lib/core", f));
}
const gz = fs.readFileSync(path.join(NM, "@tesseract.js-data/eng/4.0.0_best_int/eng.traineddata.gz"));
fs.writeFileSync(path.join(WWW, "lib/lang/eng.traineddata.txt"), gz.toString("base64"));
const osd = fs.readFileSync(path.join(NM, "@tesseract.js-data/osd/4.0.0_best_int/osd.traineddata.gz"));
fs.writeFileSync(path.join(WWW, "lib/lang/osd.traineddata.txt"), osd.toString("base64"));
fs.copyFileSync(path.join(ROOT, "www-extra/ocr-worker.js"), path.join(WWW, "lib/ocr-worker.js"));
fs.copyFileSync(path.join(ROOT, "www-extra/update.js"), path.join(WWW, "update.js"));

fs.writeFileSync(path.join(WWW, "app-config.js"), `// generated by scripts/build-www.js
window.MEDIGUARD_APP = { version: ${JSON.stringify(version)}, repo: ${JSON.stringify(repo)} };
window.MEDIGUARD_OCR = {
  workerPath: new URL("lib/ocr-worker.js", location.href).href,
  workerBlobURL: false,
  corePath: new URL("lib/core/", location.href).href,
  langPath: new URL("lib/lang", location.href).href,
};
`);

let html = fs.readFileSync(path.join(WWW, "index.html"), "utf8");
html = html.replace('<link rel="manifest" href="manifest.json">\n', "");
html = html.replace('<script src="data/medicines.js"></script>',
  '<script src="app-config.js"></script>\n  <script src="data/medicines.js"></script>');
html = html.replace('<script src="app.js" defer></script>',
  '<script src="app.js" defer></script>\n  <script src="update.js" defer></script>');
if (!html.includes("app-config.js") || !html.includes("update.js")) throw new Error("index.html layout changed");
fs.writeFileSync(path.join(WWW, "index.html"), html);
fs.rmSync(path.join(WWW, "sw.js"), { force: true });
fs.rmSync(path.join(WWW, "manifest.json"), { force: true });
console.log(`www built: version ${version}, repo ${repo}`);
